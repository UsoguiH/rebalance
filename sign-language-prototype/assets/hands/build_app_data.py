#!/usr/bin/env python3
"""Pack the hand assets the app uses into ../../hands-data.js.

Run after download.py:  python3 build_app_data.py   (needs Pillow)
"""
import base64, io, json, os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'hands-data.js')
TONES = ['default', 'light', 'medium-light', 'medium', 'medium-dark', 'dark']
# Fluent 3D hands drawn on the signer, one per handshape the lessons use
HANDS = ['raised_hand', 'rightwards_hand', 'hand_fingers_splayed', 'palm_up_hand', 'raised_fist',
         'index_pointing_up', 'pinched_fingers', 'pinching_hand', 'raised_back_of_hand']
# Noto animations for feedback moments
LOTTIE = ['thumbs_up', 'clapping_hands', 'waving_hand']


def png_uri(path, size=96):
    im = Image.open(path).convert('RGBA')
    im.thumbnail((size, size), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


def skin(path):
    """Average colour of the opaque middle of the palm, used for the signer's face."""
    im = Image.open(path).convert('RGBA').resize((64, 64))
    px = [im.getpixel((x, y)) for x in range(20, 44) for y in range(28, 52)]
    px = [p for p in px if p[3] > 250]
    r, g, b = (sum(p[i] for p in px) // len(px) for i in range(3))
    return '#%02x%02x%02x' % (r, g, b), '#%02x%02x%02x' % (int(r * .82), int(g * .82), int(b * .82))


data = {'img': {}, 'skin': {}, 'lottie': {}}
for tone in TONES:
    folder = os.path.join(HERE, '1-fluent-emoji-3d', tone)
    data['img'][tone] = {h: png_uri(os.path.join(folder, f'{h}.png')) for h in HANDS}
    data['skin'][tone] = skin(os.path.join(folder, 'raised_hand.png'))
for name in LOTTIE:
    with open(os.path.join(HERE, '2-noto-animated-emoji', f'{name}.json')) as f:
        data['lottie'][name] = json.load(f)

with open(OUT, 'w') as f:
    f.write('/* Generated by assets/hands/build_app_data.py. Fluent Emoji (MIT), Noto Emoji Animation by Google (CC BY 4.0). */\n')
    f.write('window.HANDS=' + json.dumps(data, separators=(',', ':')) + ';\n')
print(OUT, os.path.getsize(OUT), data['skin'])
