#!/usr/bin/env python3
"""Pack the character SVGs into ../../characters.js for the app.

Run after editing abu-saad.svg or saud.svg:  python3 build.py
Skin colours become CSS variables so the characters follow the learner's skin tone.
"""
import json, os, re
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'characters.js')
NS = 'http://www.w3.org/2000/svg'
ET.register_namespace('', NS)
SKIN = {'#F1A06C': 'var(--skin)', '#EE9A66': 'var(--skin)', '#E98C58': 'var(--skin-line)',
        '#E4885A': 'var(--skin-line)', '#DB8352': 'var(--skin-line)'}


def tint(markup):
    markup = re.sub(r'\s*xmlns="[^"]+"', '', markup)
    markup = re.sub(r'\s*(fill|stroke)="(#[0-9A-Fa-f]{6})"',
                    lambda m: f' style="{m.group(1)}:{SKIN[m.group(2).upper()]}"' if m.group(2).upper() in SKIN else m.group(0), markup)
    return re.sub(r'>\s+<', '><', markup).strip()


def load(name):
    root = ET.parse(os.path.join(HERE, name)).getroot()
    defs = root.find(f'{{{NS}}}defs')
    defs_markup = ''
    if defs is not None:
        defs_markup = ''.join(ET.tostring(c, encoding='unicode') for c in defs)
        root.remove(defs)
    head = root.find(f".//{{{NS}}}g[@class='head']")
    full = ''.join(ET.tostring(c, encoding='unicode') for c in root)
    return tint(full), tint(ET.tostring(head, encoding='unicode')), tint(defs_markup)


abu_full, abu_head, abu_defs = load('abu-saad.svg')
saud_full, saud_head, _ = load('saud.svg')
data = {'defs': abu_defs,
        'abu': {'name': 'أبو سعد', 'full': abu_full, 'head': abu_head, 'view': '100 30 220 350'},
        'saud': {'name': 'سعود', 'full': saud_full, 'head': saud_head, 'view': '66 48 222 334'}}
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* Generated by assets/characters/build.py from abu-saad.svg and saud.svg. */\n')
    f.write('window.CHARS=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(OUT, os.path.getsize(OUT))
