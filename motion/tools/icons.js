// Pulls brand marks from Simple Icons (pinned version) into js/icons.js, so the
// pieces can draw real logos with no runtime dependency.
//   node motion/tools/icons.js
// Simple Icons is CC0; the marks themselves are trademarks of their owners.
const fs = require('fs');
const path = require('path');
const https = require('https');

const VERSION = '16.35.0';
const SLUGS = [
  // Jira piece
  'jira', 'atlassian', 'confluence', 'trello', 'bitbucket', 'gmail', 'googlesheets', 'googlecalendar',
  'notion', 'github', 'figma', 'zoom', 'asana',
  // One Button piece
  'apple', 'claude', 'googlegemini', 'perplexity',
];

const get = (url) =>
  new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode !== 200) return reject(new Error(`${res.statusCode} ${url}`));
        let body = '';
        res.setEncoding('utf8');
        res.on('data', (d) => (body += d));
        res.on('end', () => resolve(body));
      })
      .on('error', reject);
  });

(async () => {
  const base = `https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}`;
  const data = JSON.parse(await get(`${base}/data/simple-icons.json`));
  const list = Array.isArray(data) ? data : data.icons;
  const slugOf = (i) =>
    i.slug ||
    i.title
      .toLowerCase()
      .replace(/\+/g, 'plus')
      .replace(/^\./, 'dot-')
      .replace(/\./g, '-dot-')
      .replace(/&/g, 'and')
      .normalize('NFD')
      .replace(/[^a-z0-9]/g, '');
  const icons = {};
  for (const slug of SLUGS) {
    const svg = await get(`${base}/icons/${slug}.svg`);
    const d = /<path d="([^"]+)"/.exec(svg)[1];
    const meta = list.find((i) => slugOf(i) === slug);
    icons[slug] = { title: meta ? meta.title : slug, hex: meta ? meta.hex : '000000', path: d };
  }
  const out =
    `// Generated by tools/icons.js from Simple Icons ${VERSION} (CC0, simpleicons.org).\n` +
    '// The marks are trademarks of their respective owners. 24x24 viewBox paths.\n' +
    `M.ICONS = ${JSON.stringify(icons, null, 1)};\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'js', 'icons.js'), out);
  console.log('wrote js/icons.js:', Object.keys(icons).join(', '));
})();
