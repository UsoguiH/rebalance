"""Turn the picked candidates into app assets.

picks.json maps style id -> candidate index, or [index, focus_x, focus_y, zoom]
(focus 0..1 inside the source photo, zoom >= 1 crops tighter).
Writes assets/styles/<id>.jpg (600x800), js/styles.js and credits.html.

usage: python3 build_assets.py <cands_dir>
"""
import html, json, os, sys, time
from PIL import Image, ImageOps
from find_candidates import get

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
W, H = 600, 800

LICENSE_NAMES = {"by": "CC BY", "by-sa": "CC BY-SA", "cc0": "CC0", "pdm": "Public Domain Mark"}


def crop(im, fx, fy, zoom):
    im = ImageOps.exif_transpose(im).convert("RGB")
    w, h = im.size
    cw = min(w, h * 3 / 4) / zoom
    ch = cw * 4 / 3
    x = min(max(fx * w - cw / 2, 0), w - cw)
    y = min(max(fy * h - ch / 2, 0), h - ch)
    return im.crop((round(x), round(y), round(x + cw), round(y + ch))).resize((W, H), Image.LANCZOS)


def license_label(c):
    lic = c.get("license") or ""
    name = LICENSE_NAMES.get(lic, lic)
    if c.get("license_version") and lic in ("by", "by-sa"):
        name += " " + c["license_version"]
    return name


def main():
    d = sys.argv[1]
    styles = json.load(open(os.path.join(HERE, "styles.json")))
    desc = json.load(open(os.path.join(HERE, "descriptions.json")))
    picks = json.load(open(os.path.join(HERE, "picks.json")))
    cands = json.load(open(os.path.join(d, "candidates.json")))
    cm_path = os.path.join(d, "commons.json")
    commons = json.load(open(cm_path)) if os.path.exists(cm_path) else {}
    out_dir = os.path.join(ROOT, "assets", "styles")
    os.makedirs(out_dir, exist_ok=True)
    data, missing = [], []
    for kind in ("hair", "beard"):
        for sid, name, _q, _cat in styles[kind]:
            p = picks.get(sid)
            if p is None:
                missing.append(sid)
                continue
            if not isinstance(p, list):
                p = [p]
            idx, fx, fy, zoom = (p + [0.5, 0.4, 1.0][len(p) - 1:])[:4]
            if str(idx).startswith("c"):  # Wikimedia Commons: fetch a bigger rendition
                c = commons[sid][int(idx[1:])]
                src = os.path.join(d, "big", sid + ".jpg")
                if not os.path.exists(src):
                    os.makedirs(os.path.dirname(src), exist_ok=True)
                    big = (c.get("thumb") or c["url"]).replace("/330px-", "/960px-")
                    raw = get(big, tries=3) or get(c["url"], tries=3)
                    open(src, "wb").write(raw)
                    time.sleep(2)
            else:
                c = cands[sid][int(idx)]
                src = os.path.join(d, "thumbs", sid, "%02d.jpg" % int(idx))
            crop(Image.open(src), fx, fy, zoom).save(os.path.join(out_dir, sid + ".jpg"), quality=80, optimize=True, progressive=True)
            data.append({
                "id": sid, "kind": kind, "name": name, "desc": desc[sid],
                "img": "assets/styles/%s.jpg" % sid,
                "credit": {"author": c["author"], "license": license_label(c),
                           "licenseUrl": c.get("license_url"), "source": c.get("page") or c["url"],
                           "title": c.get("title", "")},
            })
    with open(os.path.join(ROOT, "js", "styles.js"), "w") as f:
        f.write("/* Generated by tools/build_assets.py. Real reference photos, openly licensed; see credits.html. */\n")
        f.write("window.STYLES = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
    rows = []
    for s in data:
        c = s["credit"]
        lic = html.escape(c["license"])
        if c.get("licenseUrl"):
            lic = '<a href="%s">%s</a>' % (html.escape(c["licenseUrl"]), lic)
        rows.append('<li><img src="%s" alt="" loading="lazy"><div><b>%s</b><span>%s</span><span>Photo by %s · %s · <a href="%s">source</a></span></div></li>' % (
            s["img"], html.escape(s["name"]), "Haircut" if s["kind"] == "hair" else "Beard",
            html.escape(c["author"]), lic, html.escape(c["source"])))
    page = open(os.path.join(HERE, "credits.template.html")).read().replace("<!--ROWS-->", "\n".join(rows))
    open(os.path.join(ROOT, "credits.html"), "w").write(page)
    print(len(data), "styles built; missing:", missing)


if __name__ == "__main__":
    main()
