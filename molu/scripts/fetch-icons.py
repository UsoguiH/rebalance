# Fetch Google Material Symbols (Rounded, outline + filled) into js/icons.js. Apache-2.0.
import subprocess, re, json, sys
names = """home search calendar_month favorite person content_cut palette air brush visibility back_hand self_care
face_retouching_natural draw face_6 face_3 child_care star location_on near_me schedule tune map list close check arrow_back
chevron_left chevron_right expand_more expand_less add remove notifications storefront verified local_offer event_available
check_circle call chat ios_share bookmark payments credit_card workspace_premium groups badge qr_code_2 trending_up bolt
notifications_active rate_review language logout apartment person_add login sell home_work spa wc diversity_1 sentiment_satisfied
storefront event_busy lock edit_calendar timer cancel info apps apparel water_drop
percent redeem local_fire_department history grid_view shopping_bag package_2 discount celebration keyboard_arrow_down arrow_forward
link touch_app content_copy photo_camera share""".split()
out, vb = {}, {}
for n in names:
    for fill in ('', '_fill1'):
        url = f"https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{n}/materialsymbolsrounded/{n}{fill}_24px.svg"
        svg = subprocess.run(['curl', '-sf', url], capture_output=True, text=True).stdout
        d = re.search(r'<path d="([^"]+)"', svg)
        if not d: print('missing', n, fill, file=sys.stderr); continue
        v = re.search(r'viewBox="([^"]+)"', svg); view = v.group(1) if v else '0 0 24 24'
        k = n + ('_f' if fill else '')
        out[k] = d.group(1)
        if view != '0 -960 960 960': vb[k] = view
js = ("// Google Material Symbols (Rounded) — Apache-2.0. Generated by scripts/fetch-icons.py\n"
      f"export const MS = {json.dumps(out)};\nconst VB = {json.dumps(vb)};\n"
      "export const icon = (name, size = 24, cls = '') => {\n"
      "  const k = MS[name] ? name : name.replace(/_f$/, '');\n"
      "  return `<svg class=\"ms ${cls}\" viewBox=\"${VB[k] || '0 -960 960 960'}\" width=\"${size}\" height=\"${size}\" aria-hidden=\"true\"><path fill=\"currentColor\" d=\"${MS[k] || ''}\"/></svg>`;\n};\n")
open('js/icons.js', 'w').write(js)
print(len(out), 'paths; custom viewBox:', list(vb))
